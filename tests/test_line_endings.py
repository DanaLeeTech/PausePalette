"""Line-ending fidelity: a CRLF slice must stay CRLF once pauses are inserted.

Windows-authored / editor-rewritten G-code uses CRLF. The pause block has to be
written with the file's own ending, or the export ends up with mixed endings.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pausepalette.editor import insert_pauses  # noqa: E402
from pausepalette.gcode import detect_newline, parse_gcode  # noqa: E402
from pausepalette.pipeline import (  # noqa: E402
    insert_into_slice,
    plan_and_insert,
)
from pausepalette.planner import plan_for_gcode  # noqa: E402
from pausepalette.verifier import verify  # noqa: E402
from tests.fixtures import keychain_gcode  # noqa: E402

RED, GREEN, BLUE = "#E4002B", "#20C463", "#0A84FF"


def _orca_slice(model: str, colours: list[str], tools: list[int], newline: str = "\n") -> str:
    """A non-Bambu slice (config block at the end), with a chosen ending."""
    changes = [(t, i) for i, t in enumerate(tools, start=1)]
    lines = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer 2.4.2",
        f"; total layer number: {len(changes)}",
        "; HEADER_BLOCK_END",
        "",
        "G28",
        "G90",
        "M83",
    ]
    for tool, layer in changes:
        lines += [
            ";LAYER_CHANGE",
            f"; layer num/total_layer_count: {layer}/{len(changes)}",
            f"T{tool}",
            "G1 X10 Y10 E1",
        ]
    lines += [
        "; CONFIG_BLOCK_START",
        "; filament_colour = " + ";".join(colours),
        "; filament_type = PLA",
        f"; printer_model = {model}",
        "; CONFIG_BLOCK_END",
        "",
    ]
    return newline.join(lines) + newline


def _bare_lf(text: str) -> list[str]:
    """Lines that end with a bare LF in a file that is otherwise CRLF."""
    return [
        ln for ln in text.splitlines(keepends=True)
        if ln.endswith("\n") and not ln.endswith("\r\n")
    ]


def test_detect_newline():
    assert detect_newline("a\r\nb\r\n") == "\r\n"
    assert detect_newline("a\nb\n") == "\n"
    assert detect_newline("") == "\n"
    assert detect_newline("no newline at all") == "\n"
    # the dominant ending wins; a tie falls back to LF
    assert detect_newline("a\r\nb\r\nc\n") == "\r\n"
    assert detect_newline("a\r\nb\n") == "\n"


def test_bambu_crlf_file_is_edited_in_crlf():
    text = keychain_gcode().replace("\n", "\r\n")
    gf = parse_gcode(text)
    assert all(ln.endswith("\r\n") for ln in gf.lines)   # import keeps the endings

    plan = plan_for_gcode(gf, slots=4)
    result = insert_pauses(gf, plan)                      # export detects CRLF
    assert not _bare_lf(result.text)
    assert "M400 U1 ; PAUSE: swap spools now, then resume\r\n" in result.text
    assert verify(gf, result, plan).ok


def test_bambu_crlf_through_single_stage_pipeline():
    data = keychain_gcode().replace("\n", "\r\n").encode("utf-8")
    result = plan_and_insert(data, slots=4)
    assert result.report.ok
    assert not _bare_lf(result.edited.text)


def test_bambu_crlf_through_stage3():
    text = keychain_gcode().replace("\n", "\r\n")
    plan = plan_for_gcode(parse_gcode(text), slots=4)
    result = insert_into_slice(text.encode("utf-8"), plan)
    assert result.report.ok
    assert not _bare_lf(result.edited.text)


def test_generic_crlf_file_is_edited_in_crlf():
    text = _orca_slice("Voron 2.4 300", [RED, GREEN], [0, 1, 0, 1], newline="\r\n")
    gf = parse_gcode(text)
    plan = plan_for_gcode(gf, slots=1)
    result = insert_pauses(gf, plan)
    assert not _bare_lf(result.text)
    assert verify(gf, result, plan).ok


def test_generic_crlf_through_single_stage_pipeline():
    data = _orca_slice("Creality Ender-3", [RED, GREEN, BLUE], [0, 1, 0, 2], newline="\r\n")
    result = plan_and_insert(data.encode("utf-8"), slots=1)
    assert result.report.ok
    assert not _bare_lf(result.edited.text)


def test_lf_files_are_not_turned_into_crlf():
    result = plan_and_insert(keychain_gcode().encode("utf-8"), slots=4)
    assert result.report.ok
    assert "\r" not in result.edited.text


def test_explicit_newline_override_still_wins():
    gf = parse_gcode(keychain_gcode())
    plan = plan_for_gcode(gf, slots=4)
    result = insert_pauses(gf, plan, newline="\r\n")
    assert "M400 U1 ; PAUSE: swap spools now, then resume\r\n" in result.text
