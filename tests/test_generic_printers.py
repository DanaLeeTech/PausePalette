"""Other printers: the pause comes from the slicer's own printer profile.

The shape of these files was taken from a real OrcaSlicer 2.4.2 slice for a
non-Bambu machine: a header block at the top, a bare ``T<n>`` for every colour
change (OrcaSlicer and PrusaSlicer write exactly that when the printer has no
custom change-filament G-code), and the config block — the filament list and
the printer model — at the *end* of the file.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pausepalette.dialects import generic  # noqa: E402
from pausepalette.editor import insert_pauses  # noqa: E402
from pausepalette.errors import StopAndExplain  # noqa: E402
from pausepalette.gcode import parse_gcode  # noqa: E402
from pausepalette.planner import plan_for_gcode  # noqa: E402
from pausepalette.verifier import verify  # noqa: E402

RED, GREEN, BLUE = "#E4002B", "#20C463", "#0A84FF"


def orca_slice(model: str, colours: list[str], tools: list[int],
               change: list[str] | None = None) -> str:
    """A non-Bambu slice, laid out the way OrcaSlicer lays one out."""
    changes = [(tool, i) for i, tool in enumerate(tools, start=1)]
    return orca_slice_changes(model, colours, changes, change=change)


def orca_slice_changes(model: str, colours: list[str], changes: list[tuple[int, int]],
                       change: list[str] | None = None) -> str:
    """Same file, but with an explicit (tool, layer) for every change."""
    total = max(layer for _, layer in changes) if changes else 1
    lines = [
        "; HEADER_BLOCK_START",
        "; generated by OrcaSlicer 2.4.2 on 2026-10-17 at 10:00:00",
        f"; total layer number: {total}",
        "; HEADER_BLOCK_END",
        "",
        "G28",
        "G90",
        "M83",
    ]
    for tool, layer in changes:
        lines += [
            ";LAYER_CHANGE",
            f"; layer num/total_layer_count: {layer}/{total}",
            f"T{tool}",
            *(change or ["G1 X10 Y10 E1"]),
        ]
    lines += [
        "; CONFIG_BLOCK_START",
        "; filament_colour = " + ";".join(colours),
        "; filament_type = PLA;PLA;PLA",
        f"; printer_model = {model}",
        "; CONFIG_BLOCK_END",
        "",
    ]
    return "\n".join(lines) + "\n"


def test_a_non_bambu_slice_is_recognised_and_read():
    text = orca_slice("Voron 2.4 300", [RED, GREEN], [0, 1, 1, 0])
    gf = parse_gcode(text)
    assert gf.dialect == "generic"          # not M620 blocks
    assert gf.filaments == [RED, GREEN]     # read from the config block at the end
    assert gf.printer_model == "Voron 2.4 300"
    assert [(b.tool, b.layer) for b in gf.tool_changes] == [(0, 1), (1, 2), (1, 3), (0, 4)]


@pytest.mark.parametrize(
    "model,expected",
    [
        ("Voron 2.4 300", "PAUSE"),      # Klipper profile
        ("Creality Ender-3", "M600"),    # Marlin profile, change wins over `M25`
        ("Prusa MK3S", "M601"),          # Prusa profile
        ("Generic Klipper Printer", "PAUSE"),
        ("Generic Marlin Printer", "M601"),
    ],
)
def test_the_printer_itself_decides_how_to_pause(model, expected):
    gf = parse_gcode(orca_slice(model, [RED, GREEN], [0, 1, 0, 1]))
    plan = plan_for_gcode(gf, slots=1)          # one spool: swap at every change
    result = insert_pauses(gf, plan)
    report = verify(gf, result, plan)

    assert generic.pause_command(model) == expected
    assert result.text.count(f"\n{expected}\n") >= len(plan.pauses)
    assert report.ok, report.failures()


def test_the_files_own_change_sequence_is_left_alone():
    """No block rewriting outside Bambu — the machine's own G-code survives."""
    change = ["M600", "G1 E0.3 F1500 ; prime after color change"]
    text = orca_slice("Prusa MK3S", [RED, GREEN], [0, 1, 2], change=change)
    gf = parse_gcode(text)
    plan = plan_for_gcode(gf, slots=2)
    result = insert_pauses(gf, plan)

    for line in change:
        assert result.text.count(line) == text.count(line)
    assert verify(gf, result, plan).ok


def test_a_bambu_slice_still_uses_the_bambu_path():
    """The generic path must not swallow Bambu files."""
    from tests.fixtures import keychain_gcode

    gf = parse_gcode(keychain_gcode())
    assert gf.dialect == "bambu"
    plan = plan_for_gcode(gf, slots=4)
    result = insert_pauses(gf, plan)
    assert "M400 U1 ; PAUSE: swap spools now, then resume" in result.text
    assert "T255" in result.text


def test_an_unknown_printer_stops_and_explains():
    text = orca_slice("Somebody's Custom Printer", [RED, GREEN], [0, 1, 0])
    gf = parse_gcode(text)
    assert generic.pause_command("Somebody's Custom Printer") is None
    plan = plan_for_gcode(gf, slots=1)
    with pytest.raises(StopAndExplain) as excinfo:
        insert_pauses(gf, plan)
    assert "does not know how to pause" in str(excinfo.value)


def test_a_pause_that_does_not_park_is_warned_about():
    # the Ender-3 V2's profile pauses with a bare `M0`
    text = orca_slice("Creality Ender-3 V2", [RED, GREEN], [0, 1, 0])
    gf = parse_gcode(text)
    plan = plan_for_gcode(gf, slots=1)
    insert_pauses(gf, plan)
    assert any("does not park or retract" in w for w in plan.warnings)


def test_the_plan_is_the_same_whatever_the_printer():
    """Planning and reordering never look at the machine.

    The same print, written as a Bambu AMS slice and as a non-Bambu slice with
    plain ``T<n>`` changes, must plan identically — only the G-code edit differs.
    """
    from tests.fixtures import keychain_gcode

    bambu = parse_gcode(keychain_gcode())
    changes = [(b.tool, b.layer) for b in bambu.tool_changes]
    other = parse_gcode(
        orca_slice_changes("Voron 2.4 300", bambu.filaments, changes)
    )
    assert bambu.dialect == "bambu" and other.dialect == "generic"

    a = plan_for_gcode(bambu, slots=4)
    b = plan_for_gcode(other, slots=4)

    def shape(plan):
        return (
            plan.initial,
            plan.swaps_total,
            plan.colour_moves,
            [(p.index, p.layer, p.tool, p.anchor_ordinal,
              [(s.position, s.out_tool, s.in_tool) for s in p.swaps])
             for p in plan.pauses],
        )

    assert shape(a) == shape(b)          # identical plan
    assert bambu.filaments == other.filaments

    # ...and only the edit differs
    a_out = insert_pauses(bambu, a)
    b_out = insert_pauses(other, b)
    assert "M400 U1 ; PAUSE: swap spools now, then resume" in a_out.text
    assert "T255" in a_out.text                      # the Bambu cut-and-retract
    assert "PAUSE" in b_out.text                     # the Voron's own pause
    assert "T255" not in b_out.text
    assert a_out.text.count("; ===== MANUAL SPOOL SWAP ") == len(a.pauses)
    assert b_out.text.count("; ===== MANUAL SPOOL SWAP ") == len(b.pauses)
    assert verify(bambu, a_out, a).ok and verify(other, b_out, b).ok

    # the non-Bambu file is only added to, never rewritten: every original line
    # still appears, in order, in the edited file
    edited_lines = iter(b_out.text.splitlines())
    assert all(
        any(line.rstrip("\n") == original.rstrip("\n") for line in edited_lines)
        for original in other.lines
        if original.strip()
    )
